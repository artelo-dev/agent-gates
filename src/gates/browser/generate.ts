/**
 * Generators for the Playwright files browser gates run. Output is plain ESM JavaScript (.mjs)
 * so Playwright needs no TypeScript transform; every spec-derived value is embedded through
 * JSON.stringify, never spliced into code as raw text.
 */
import type { Spec } from '../../contracts.js';

export interface RouteTarget {
  /** File-name-safe id (page id or slugified route). */
  id: string;
  route: string;
}

export interface FormField {
  name: string;
  type?: string;
  required?: boolean;
}

export interface SmokePage {
  id: string;
  route: string;
  sections: string[];
}

export interface SmokeForm {
  page: string;
  route: string;
  section: string;
  fields: FormField[];
  /** Success text from the spec; asserted visible after submit when present. */
  success?: string;
}

export interface SmokePlan {
  pages: SmokePage[];
  forms: SmokeForm[];
}

export function slugifyRoute(route: string): string {
  const slug = route.replace(/^\/+|\/+$/g, '').replace(/[^\w-]+/g, '-').replace(/^-+|-+$/g, '');
  return slug || 'home';
}

const isDynamicRoute = (route: string) => /[[\]:*]/.test(route);

/** Routes for browser gates: gates.yaml `routes`, else static spec page routes, else `/`. */
export function resolveRoutes(spec: Spec | undefined, configured?: readonly string[]): RouteTarget[] {
  const seen = new Set<string>();
  const out: RouteTarget[] = [];
  const add = (id: string, route: string) => {
    const normalized = route.startsWith('/') ? route : `/${route}`;
    if (seen.has(normalized) || isDynamicRoute(normalized)) return;
    seen.add(normalized);
    let unique = id.replace(/[^\w-]+/g, '-') || 'page';
    while (out.some((r) => r.id === unique)) unique += '-x';
    out.push({ id: unique, route: normalized });
  };
  if (configured && configured.length > 0) for (const r of configured) add(slugifyRoute(r), r);
  else for (const page of spec?.pages ?? []) add(page.id, page.route);
  if (out.length === 0) add('home', '/');
  return out;
}

function asFields(value: unknown): FormField[] | undefined {
  if (!Array.isArray(value)) return undefined;
  const fields: FormField[] = [];
  for (const raw of value) {
    if (typeof raw !== 'object' || raw === null) continue;
    const f = raw as Record<string, unknown>;
    if (typeof f.name !== 'string' || f.name === '') continue;
    const field: FormField = { name: f.name };
    if (typeof f.type === 'string') field.type = f.type;
    if (f.required === true) field.required = true;
    fields.push(field);
  }
  return fields.length > 0 ? fields : undefined;
}

/** Which sections/forms the smoke test checks, derived from the spec. */
export function buildSmokePlan(spec: Spec): SmokePlan {
  const pages: SmokePage[] = [];
  const forms: SmokeForm[] = [];
  for (const page of spec.pages) {
    if (isDynamicRoute(page.route)) continue;
    pages.push({ id: page.id, route: page.route, sections: page.sections.map((s) => s.id) });
    for (const section of page.sections) {
      const fields = asFields(section.content?.fields);
      if (!fields) continue;
      const form: SmokeForm = { page: page.id, route: page.route, section: section.id, fields };
      const success = section.content?.success;
      if (typeof success === 'string' && success.trim()) form.success = success.trim();
      forms.push(form);
    }
  }
  return { pages, forms };
}

const HEADER = '// Generated by agent-gates from the project spec. Do not edit: regenerated on every gate run.\n';

/**
 * Example value from a text field's placeholder ("e.g. Mila, Border Collie" → "Mila, Border Collie"),
 * or null when the placeholder is not an example. Forms often validate a format their placeholder
 * shows; a generic "agent-gates smoke test" fails such a check and the smoke test never sees a POST.
 * Embedded verbatim in the generated spec (plain JS, no closures).
 */
export function sampleFromPlaceholder(placeholder: string | null | undefined): string | null {
  if (!placeholder) return null;
  const v = placeholder
    .trim()
    .replace(/^(e\.g\.|eg\.?|for example|such as|example|ex\.?)\s*[:,]?\s*/i, '')
    .replace(/[….]+$/, '')
    .trim();
  if (v.length < 2 || v.length > 120) return null;
  if (/^(your|enter|type|write|select|choose|optional)\b/i.test(v)) return null;
  return v;
}

/**
 * Playwright smoke test: every `[data-section]` id from the spec is present on its page, and each
 * spec form (a section with `content.fields`) fills and submits against a mocked `/api/` endpoint.
 * `outDir` receives one JSON file per page with the missing section ids.
 */
export function generateSmokeTest(plan: SmokePlan, opts: { outDir: string; mockPathPrefix?: string }): string {
  return `${HEADER}import { test, expect } from '@playwright/test';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const PAGES = ${JSON.stringify(plan.pages, null, 2)};
const FORMS = ${JSON.stringify(plan.forms, null, 2)};
const OUT_DIR = ${JSON.stringify(opts.outDir)};
const MOCK_PREFIX = ${JSON.stringify(opts.mockPathPrefix ?? '/api/')};

const sectionSelector = (id) => '[data-section=' + JSON.stringify(id) + ']';

function sampleValue(field, type) {
  const t = (type || field.type || 'text').toLowerCase();
  if (t === 'email') return 'smoke@agent-gates.test';
  if (t === 'tel') return '+15555550100';
  if (t === 'url') return 'https://smoke.agent-gates.test';
  if (t === 'number' || t === 'range') return '1';
  if (t === 'date') return '2030-01-01';
  return 'agent-gates smoke test';
}

${sampleFromPlaceholder.toString()}

// Why a submit sent no POST: the fields the page marks invalid and the messages it shows.
async function submitBlockedReason(form) {
  return form.evaluate((node) => {
    const bad = [...node.querySelectorAll('[aria-invalid="true"], :invalid')].filter((el) => el.name);
    const fields = bad.map((el) => {
      const ids = (el.getAttribute('aria-describedby') || '').split(/\\s+/).filter(Boolean);
      const msg = ids.map((id) => document.getElementById(id)?.textContent?.trim()).filter(Boolean).join(' ') || el.validationMessage || '';
      return el.name + (msg ? ' (' + msg + ')' : '');
    });
    const status = [...node.querySelectorAll('[role="status"], [role="alert"]')].map((el) => el.textContent.trim()).filter(Boolean);
    return [fields.length ? 'invalid fields: ' + [...new Set(fields)].join('; ') : 'no field marked invalid', status.length ? 'form says: ' + status.join(' / ') : ''].filter(Boolean).join('; ');
  });
}

for (const p of PAGES) {
  test('page ' + p.id + ' (' + p.route + ') has every spec [data-section]', async ({ page }) => {
    const response = await page.goto(p.route);
    expect(response, 'navigation to ' + p.route).not.toBeNull();
    expect(response.status(), 'HTTP status of ' + p.route).toBeLessThan(400);
    const missing = [];
    for (const id of p.sections) {
      if ((await page.locator(sectionSelector(id)).count()) === 0) missing.push(id);
    }
    writeFileSync(join(OUT_DIR, 'sections-' + p.id + '.json'), JSON.stringify({ page: p.id, route: p.route, expected: p.sections, missing }));
    expect(missing, 'sections missing on ' + p.route + ' (expected [data-section="<id>"])').toEqual([]);
  });
}

for (const f of FORMS) {
  test('form in section ' + f.section + ' (' + f.route + ') submits', async ({ page }) => {
    await page.route((url) => url.pathname.startsWith(MOCK_PREFIX), async (route) => {
      if (route.request().method() === 'POST') {
        await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ ok: true }) });
      } else {
        await route.continue();
      }
    });
    await page.goto(f.route);
    const form = page.locator(sectionSelector(f.section)).first().locator('form').first();
    await expect(form, 'form inside [data-section="' + f.section + '"]').toBeVisible();
    for (const field of f.fields) {
      const el = form.locator('[name=' + JSON.stringify(field.name) + ']').first();
      if ((await el.count()) === 0) {
        if (field.required) throw new Error('required field "' + field.name + '" not found in form');
        continue;
      }
      const tag = await el.evaluate((node) => node.tagName.toLowerCase());
      const type = ((await el.getAttribute('type')) || '').toLowerCase();
      if (tag === 'select') {
        const values = await el.locator('option').evaluateAll((opts) => opts.map((o) => o.value).filter((v) => v !== ''));
        if (values.length > 0) await el.selectOption(values[0]);
      } else if (type === 'checkbox' || type === 'radio') {
        await el.check();
      } else {
        const t = type || field.type || 'text';
        const fromPlaceholder = ['text', 'textarea', 'search', ''].includes(t) ? sampleFromPlaceholder(await el.getAttribute('placeholder')) : null;
        await el.fill(fromPlaceholder ?? sampleValue(field, type));
      }
    }
    const posted = page.waitForRequest((req) => req.method() === 'POST', { timeout: 10000 }).then(() => true, () => false);
    await form.locator('[type="submit"], button:not([type])').first().click();
    if (!(await posted)) {
      throw new Error('submit sent no POST within 10s: ' + (await submitBlockedReason(form)) +
        ' — the smoke test fills text fields with their placeholder example (else "agent-gates smoke test"), emails with smoke@agent-gates.test, phones with +15555550100: client-side validation must accept these.');
    }
    if (f.success) {
      await expect(page.getByText(f.success, { exact: false }).first(), 'success message after submit').toBeVisible({ timeout: 10000 });
    }
  });
}
`;
}

/** axe-core scan of every route; violations go to `<outDir>/axe-<id>.json` (the gate evaluates them). */
export function generateAxeTest(routes: readonly RouteTarget[], opts: { outDir: string; tags?: readonly string[] }): string {
  return `${HEADER}import { test } from '@playwright/test';
import * as axeModule from '@axe-core/playwright';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const AxeBuilder = axeModule.default?.default ?? axeModule.default ?? axeModule.AxeBuilder;
const ROUTES = ${JSON.stringify(routes, null, 2)};
const OUT_DIR = ${JSON.stringify(opts.outDir)};
const TAGS = ${JSON.stringify(opts.tags ?? ['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'])};

for (const r of ROUTES) {
  test('axe ' + r.route, async ({ page }) => {
    await page.goto(r.route);
    const results = await new AxeBuilder({ page }).withTags(TAGS).analyze();
    const violations = results.violations.map((v) => ({
      id: v.id,
      impact: v.impact ?? 'minor',
      help: v.help,
      helpUrl: v.helpUrl,
      count: v.nodes.length,
      targets: v.nodes.slice(0, 5).map((n) => [].concat(n.target).join(' ')),
    }));
    writeFileSync(join(OUT_DIR, 'axe-' + r.id + '.json'), JSON.stringify({ route: r.route, violations }, null, 2));
  });
}
`;
}

/**
 * Full-page screenshots per route × viewport width plus a horizontal-overflow probe (the cheap,
 * scriptable part of "no broken layout"; the Reviewer looks at the images).
 */
export function generateVisualTest(routes: readonly RouteTarget[], opts: { outDir: string; viewports: readonly number[]; height?: number }): string {
  return `${HEADER}import { test } from '@playwright/test';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROUTES = ${JSON.stringify(routes, null, 2)};
const WIDTHS = ${JSON.stringify(opts.viewports)};
const HEIGHT = ${JSON.stringify(opts.height ?? 900)};
const OUT_DIR = ${JSON.stringify(opts.outDir)};

for (const r of ROUTES) {
  for (const width of WIDTHS) {
    test('screenshot ' + r.route + ' @' + width, async ({ page }) => {
      await page.setViewportSize({ width, height: HEIGHT });
      await page.goto(r.route, { waitUntil: 'load' });
      await page.evaluate(async () => { if (document.fonts) await document.fonts.ready; });
      const m = await page.evaluate(() => ({ scrollWidth: document.documentElement.scrollWidth, innerWidth: window.innerWidth }));
      const file = r.id + '-' + width + '.png';
      await page.screenshot({ path: join(OUT_DIR, file), fullPage: true });
      writeFileSync(
        join(OUT_DIR, 'visual-' + r.id + '-' + width + '.json'),
        JSON.stringify({ route: r.route, width, file, scrollWidth: m.scrollWidth, overflow: m.scrollWidth > m.innerWidth + 1 }),
      );
    });
  }
}
`;
}

/** Playwright config for one generated suite (plain object, so it needs no import to load). */
export function generatePlaywrightConfig(opts: {
  testFile: string;
  baseURL: string;
  jsonReport: string;
  outputDir: string;
  timeoutMs?: number;
}): string {
  const config = {
    testDir: '.',
    testMatch: [`**/${opts.testFile}`],
    fullyParallel: false,
    workers: 1,
    retries: 0,
    timeout: opts.timeoutMs ?? 30_000,
    reporter: [['json', { outputFile: opts.jsonReport }]],
    outputDir: opts.outputDir,
    use: { baseURL: opts.baseURL, trace: 'off', screenshot: 'only-on-failure', contextOptions: { reducedMotion: 'reduce' } },
    projects: [{ name: 'chromium', use: { browserName: 'chromium' } }],
  };
  return `${HEADER}export default ${JSON.stringify(config, null, 2)};\n`;
}
